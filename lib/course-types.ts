export type RuntimeKind = 'browser' | 'api' | 'linux' | 'gpu';
export type CoursePrediction = {
  cellId: string;
  question: string;
  options: Array<{ value: string; label: string }>;
  observation: 'exam' | 'training-errors' | 'schedule' | 'duplicate-delivery';
  denominator?: number;
  reflect: string;
  challenge: string;
};
export type CourseBlock = {
  id: string;
  type: 'prose' | 'heading' | 'code' | 'image' | 'video' | 'callout' | 'prediction';
  prediction?: CoursePrediction;
  text?: string;
  html?: string;
  level?: number;
  language?: string;
  code?: string;
  filename?: string;
  runnable?: boolean;
  predictionSample?: boolean;
  runtime?: RuntimeKind;
  src?: string;
  width?: number;
  height?: number;
  previewSrc?: string;
  previewWidth?: number;
  previewHeight?: number;
  srcSet?: string;
  poster?: string;
  subtitleSrc?: string;
  excerptNotice?: string;
  readingAlternative?: string[];
  duration?: number;
  alt?: string;
  caption?: string;
  available?: boolean;
  reason?: string;
};
export type ChapterInfo = {
  id: string;
  title: string;
  shortTitle: string;
  volume: 'upper' | 'lower';
  group: string;
  order: number;
  kind: 'chapter' | 'intro' | 'extra' | 'appendix';
  minutes: number;
  summary: string;
  text: string;
  codeCount: number;
  videoCount: number;
};
export type Chapter = ChapterInfo & {
  blocks: CourseBlock[];
  files?: Record<string, string>;
  sourceFile: string;
};
export type Term = { id: string; label: string; aliases?: string[]; definition: string; chapterId?: string };
export type CourseIndex = { title: string; subtitle: string; chapters: ChapterInfo[]; terms: Term[]; updatedAt: string; assets?: Record<string, number> };
export type GuideSource = { chapterId: string; blockId: string; title: string; excerpt?: string };
export type GuideMessage = { role: 'user' | 'assistant'; content: string; sources?: GuideSource[]; model?: string };
export type LearningState = {
  chapterId?: string;
  anchor?: string;
  fontSize?: number;
  reduceMotion?: boolean;
  bookmarks?: Array<{chapterId: string; blockId: string; title: string; savedAt: string}>;
  codes?: Record<string, string>;
  files?: Record<string, Record<string, string>>;
  predictions?: Record<string, string>;
  videoTimes?: Record<string, number>;
  chats?: Record<string, GuideMessage[]>;
};
